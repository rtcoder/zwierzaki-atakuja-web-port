def matching_brace(source: str, start: int) -> int:
    depth = 0
    for at in range(start, len(source)):
        if source[at] == '{': depth += 1
        elif source[at] == '}':
            depth -= 1
            if depth == 0: return at
    raise ValueError('Unclosed source block')


def extract_factories(source: str) -> str:
    start = source.index('    private void e(int var1_1)')
    end = source.index('    private void a(Vector vector, int n2, int n3, int n4, int n5, int n6, int n7)', start)
    block = source[start:end]
    methods = []
    for match in re.finditer(r'^            case (\d+): \{', block, re.M):
        stage = int(match.group(1))
        opening = block.index('{', match.start())
        body = block[opening+1:matching_brace(block, opening)]
        body = re.sub(r'new Vector<[^>]+>', 'new Vector', body)
        body = body.replace('if (!b.p) break;', 'if (!b.p) return;')
        body = re.sub(r'^                break;$', '                return;', body, flags=re.M)
        body = body.replace('** GOTO lbl360', 'this.a(var3_19, true, true);\n                return;')
        body = body.replace('lbl360:', '')
        declarations = []
        if stage <= 17:
            types = {'var1_2':'float','var1_3':'q','var2_12':'q','var1_5':'int[]','var2_11':'float','var2_13':'float','var4_26':'float','var5_28':'float','var1_6':'float'}
            for name in sorted(set(re.findall(r'\bvar\d+_\d+\b', body))):
                kind = 'Vector' if name.startswith('var3_') else types.get(name, 'int')
                declarations.append(f'{kind} {name};')
        if stage == 10:
            cut = body.index('var1_3 = new z')
            body = body[:cut] + body[cut:].replace('var1_3','compound10')
            declarations.append('z compound10;')
        if stage == 43:
            body = body.replace('vector = new z(vector, false, false);','z compound43 = new z(vector, false, false);')
            body = body.replace('((z)((Object)vector))','compound43').replace('this.var_bg_a.b((v)((Object)vector));','this.var_bg_a.b(compound43);')
        if re.search(r'\bvector\b', body) and not re.search(r'Vector(?:<[^>]+>)?\s+vector\s*=', body):
            declarations.append('Vector vector = null;')
        methods.append(f'    private void stage{stage}(int n2) {{\n        '+ '\n        '.join(declarations) + body + '\n    }\n')
    assert len(methods) == 50, len(methods)
    helpers = source[end:source.index('    private void a(Graphics graphics', end)]
    helpers = helpers.replace('return object;', 'return (z)object;')
    helpers = helpers.replace('int n4, boolean n5, int n6) {','int n4, boolean flag5, int n6) {\n        int n5 = flag5 ? 1 : 0;')
    # CFR moved an unconditional width division into the nonzero-type arm of
    # a ternary. Original c.a(Vector,int,int,int,boolean,int) bytecode 14-23
    # divides width and height before its type branch (37-49). Restore that
    # order so type-zero cliffs keep their actual 32-unit columns.
    folded_width = 'int n9 = n6 == 0 ? 0 : 2 * (n2 /= 32);'
    assert helpers.count(folded_width) == 1, 'Inspect changed cliff helper source'
    helpers = helpers.replace('n3 /= 32;', 'n2 /= 32;\n        n3 /= 32;', 1)
    helpers = helpers.replace(folded_width, 'int n9 = n6 == 0 ? 0 : 2 * n2;')
    return '\n'.join(methods) + helpers


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', type=Path, default=Path('/tmp/zwierzaki-recon/nokia-renamed/c.java'))
