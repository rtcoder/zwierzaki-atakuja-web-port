#!/usr/bin/env python3
"""Rebuild faithful 4x lossless game images from the immutable originals.

Requires Pillow 12.3.0. Does not generate details or alter game geometry.
"""
from __future__ import annotations

import hashlib
import json
from pathlib import Path
import re

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
SCALE = 4


def upscale(image: Image.Image, *, clean_jpeg: bool = False) -> Image.Image:
    """Interpolate in premultiplied alpha to avoid dark transparent fringes."""
    rgba = image.convert("RGBA")
    size = (rgba.width * SCALE, rgba.height * SCALE)
    if clean_jpeg:
        rgb = rgba.convert("RGB")
        rgb = Image.blend(rgb, rgb.filter(ImageFilter.MedianFilter(3)), 0.35)
        rgb = rgb.filter(ImageFilter.GaussianBlur(0.35))
        return rgb.resize(size, Image.Resampling.LANCZOS).filter(
            ImageFilter.UnsharpMask(radius=0.8, percent=60, threshold=3)
        ).convert("RGBA")
    return rgba.convert("RGBa").resize(size, Image.Resampling.LANCZOS).convert("RGBA")


def enhance(image: Image.Image, key: str, manifest: dict) -> Image.Image:
    effect = manifest["effects"].get(key)
    font = next((f for f in manifest["fonts"].values() if f["asset"] == key), None)
    if effect:
        result = Image.new("RGBA", (image.width * SCALE, image.height * SCALE))
        width, height = effect["frameWidth"], effect["frameHeight"]
        for frame in range(effect["frames"]):
            tile = image.crop((frame * width, 0, (frame + 1) * width, height))
            result.paste(upscale(tile), (frame * width * SCALE, 0))
        return result
    result = upscale(image, clean_jpeg=image.format == "JPEG")
    if font:
        # Each glyph gets its own sampling boundary, including opaque font atlases.
        for glyph in font["glyphs"].values():
            x, y, w, h = (glyph[k] for k in ("x", "y", "width", "height"))
            result.paste(upscale(image.crop((x, y, x + w, y + h))), (x * SCALE, y * SCALE))
    return result


def main() -> None:
    source_dir = ROOT / "assets-original"
    destination = ROOT / "dist/assets"
    source = json.loads((source_dir / "manifest.json").read_text())
    # Validate the entire source set before writing any output.
    for key, meta in source["assets"].items():
        digest = hashlib.sha256((source_dir / meta["file"]).read_bytes()).hexdigest()
        if digest != meta["sha256"]:
            raise ValueError(f"Original asset checksum mismatch: {key}")
    assets = {}
    for key, meta in source["assets"].items():
        with Image.open(source_dir / meta["file"]) as image:
            if image.size != (meta["width"], meta["height"]):
                raise ValueError(f"Original dimensions mismatch: {key}")
            enhanced = enhance(image, key, source)
            if enhanced.getextrema()[3] == (255, 255):
                enhanced = enhanced.convert("RGB")
            file_name = f"{key}.png"
            path = destination / file_name
            enhanced.save(path, optimize=True)
            data = path.read_bytes()
            assets[key] = {
                "file": file_name, "width": meta["width"], "height": meta["height"],
                "pixelWidth": enhanced.width, "pixelHeight": enhanced.height, "scale": SCALE,
                "bytes": len(data), "sha256": hashlib.sha256(data).hexdigest(),
                "originalFile": meta["file"], "originalSha256": meta["sha256"],
            }
    source_info = {**source["source"], "pixelPolicy": "Faithful 4x filtered upscale; originals in assets-original",
                   "processing": "Pillow 12.3.0; premultiplied-alpha Lanczos; gentle JPEG filtering; lossless PNG"}
    payload = {**source, "source": source_info, "assets": assets}
    (destination / "manifest.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n")
    module = ROOT / "dist/js/assets.js"
    js = module.read_text()
    for name, value in [("ASSET_SOURCE", source_info), ("ASSET_META", assets)]:
        replacement = f"export const {name} = " + json.dumps(value, ensure_ascii=False, separators=(",", ":")) + ";"
        js, count = re.subn(rf"^export const {name} = .*;$", lambda _: replacement, js, flags=re.MULTILINE)
        if count != 1:
            raise ValueError(f"Expected one {name} declaration")
    js = js.replace("// Generated by tools/extract-assets.py; original image bytes remain unchanged.",
                    "// Source mappings from extract-assets.py; image metadata regenerated by enhance-assets.py.")
    module.write_text(js)
    # These exact legacy files are superseded by lossless PNGs, with originals archived.
    for meta in source["assets"].values():
        if Path(meta["file"]).suffix != ".png":
            (destination / meta["file"]).unlink(missing_ok=True)
    print(f"Enhanced {len(assets)} assets at {SCALE}x; original checksums verified.")


if __name__ == "__main__":
    main()
